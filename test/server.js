function writeJsonl(filePath, records) {
  mkdirSync(path.dirname(filePath), { recursive: true });
  writeFileSync(filePath, records.map(record => JSON.stringify(record)).join('\n') + '\n');
  return filePath;
}

function message(type, text, model) {
  return {
    type,
    cwd: '/workspace/claude',
    timestamp: new Date(now).toISOString(),
    message: {
      role: type,
      model: type === 'assistant' ? model : undefined,
      content: [{ type: 'text', text }]
    }
  };
}

function startServer() {
  serverProcess = spawn(process.execPath, [CLI, '--serve', '--port', '0', '--active-minutes', '15'], {
    env: serverEnv,
    stdio: ['ignore', 'pipe', 'pipe']
  });
  serverProcess.stdout.setEncoding('utf8');
  serverProcess.stderr.setEncoding('utf8');

  return new Promise((resolve, reject) => {
    let stdout = '';
    let stderr = '';
    const timer = setTimeout(() => {
      cleanup();
      reject(new Error(`Server did not start.\n${stdout}\n${stderr}`));
    }, 10_000);
    const onStdout = chunk => {
      stdout += chunk;
      const match = stdout.match(/Sessions dashboard: (http:\/\/[^\s]+)/);
      if (match) {
        cleanup();
        resolve(match[1]);
      }
    };
    const onStderr = chunk => { stderr += chunk; };
    const onExit = code => {
      cleanup();
      reject(new Error(`Server exited with ${code}.\n${stdout}\n${stderr}`));
    };
    function cleanup() {
      clearTimeout(timer);
      serverProcess.stdout.off('data', onStdout);
      serverProcess.stderr.off('data', onStderr);
      serverProcess.off('exit', onExit);
    }
    serverProcess.stdout.on('data', onStdout);
    serverProcess.stderr.on('data', onStderr);
    serverProcess.once('exit', onExit);
  });
}

