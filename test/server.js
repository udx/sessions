#!/usr/bin/env node

import assert from 'node:assert/strict';
import { spawn } from 'node:child_process';
import { once } from 'node:events';
import {
  appendFileSync,
  mkdirSync,
  mkdtempSync,
  readFileSync,
  rmSync,
  utimesSync,
  writeFileSync
} from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const CLI = path.join(__dirname, '..', 'index.js');
const root = mkdtempSync(path.join(os.tmpdir(), 'sessions-server-'));
const claudeDir = path.join(root, 'claude');
const codexDir = path.join(root, 'codex');
const kimiDir = path.join(root, 'kimi');
const now = Date.now();
const CLAUDE_ID = 'aaaaaaaa-1111-4222-8333-aaaaaaaaaaaa';
const CODEX_ID = '019f0000-1111-7222-8333-abcdefabcdef';
const KIMI_ID = 'dddddddd-1111-4222-8333-dddddddddddd';
let serverProcess;

function writeJsonl(filePath, records) {
  mkdirSync(path.dirname(filePath), { recursive: true });
  writeFileSync(filePath, records.map(record => JSON.stringify(record)).join('\n') + '\n');
  return filePath;
}

function message(type, text, model) {
  return {
    type,
    cwd: '/workspace/claude',
    timestamp: new Date(now).toISOString(),
    message: {
      role: type,
      model: type === 'assistant' ? model : undefined,
      content: [{ type: 'text', text }]
    }
  };
}

function startServer() {
  serverProcess = spawn(process.execPath, [CLI, '--serve', '--port', '0', '--active-minutes', '15'], {
    env: {
      ...process.env,
      NO_COLOR: '1',
      SESSIONS_CLAUDE_DIR: claudeDir,
      SESSIONS_CODEX_DIR: codexDir,
      SESSIONS_KIMI_DIR: kimiDir
    },
    stdio: ['ignore', 'pipe', 'pipe']
  });
  serverProcess.stdout.setEncoding('utf8');
  serverProcess.stderr.setEncoding('utf8');

  return new Promise((resolve, reject) => {
    let stdout = '';
    let stderr = '';
    const timer = setTimeout(() => {
      cleanup();
      reject(new Error(`Server did not start.\n${stdout}\n${stderr}`));
    }, 10_000);
    const onStdout = chunk => {
      stdout += chunk;
      const match = stdout.match(/Sessions dashboard: (http:\/\/[^\s]+)/);
      if (match) {
        cleanup();
        resolve(match[1]);
      }
    };
    const onStderr = chunk => { stderr += chunk; };
    const onExit = code => {
      cleanup();
      reject(new Error(`Server exited with ${code}.\n${stdout}\n${stderr}`));
    };
    function cleanup() {
      clearTimeout(timer);
      serverProcess.stdout.off('data', onStdout);
      serverProcess.stderr.off('data', onStderr);
      serverProcess.off('exit', onExit);
    }
    serverProcess.stdout.on('data', onStdout);
    serverProcess.stderr.on('data', onStderr);
    serverProcess.once('exit', onExit);
  });
}

try {
  const claudeFile = writeJsonl(
    path.join(claudeDir, 'projects', '-workspace-claude', `${CLAUDE_ID}.jsonl`),
    [
      message('user', '<local-command-caveat>Caveat: The messages below were generated by the user while running local commands.</local-command-caveat>'),
      message('user', 'Active Claude prompt'),
      message('assistant', 'Claude response', 'claude-test')
    ]
  );
  const codexFile = writeJsonl(
    path.join(codexDir, 'sessions', '2026', '11', '07', `rollout-2026-11-07T00-00-00-test-${CODEX_ID}.jsonl`),
    [
      { type: 'session_meta', timestamp: new Date(now - 7_200_000).toISOString(), payload: { id: CODEX_ID, cwd: '/workspace/codex' } },
      { type: 'turn_context', payload: { cwd: '/workspace/codex', model: 'gpt-test' } },
      { type: 'event_msg', timestamp: new Date(now - 7_100_000).toISOString(), payload: { type: 'user_message', message: 'Past Codex prompt' } },
      { type: 'event_msg', timestamp: new Date(now - 7_000_000).toISOString(), payload: { type: 'agent_message', message: 'Codex response' } }
    ]
  );
  const kimiSessionDir = path.join(kimiDir, 'sessions', 'wd_kimi_aabbccddeeff', `session_${KIMI_ID}`);
  mkdirSync(kimiSessionDir, { recursive: true });
  writeFileSync(path.join(kimiSessionDir, 'state.json'), JSON.stringify({
    cwd: '/workspace/kimi',
    title: 'Kimi dashboard fixture',
    createdAt: now - 7_200_000,
    archived: false
  }));
  const kimiFile = writeJsonl(path.join(kimiSessionDir, 'agents', 'main', 'wire.jsonl'), [
    { type: 'llm.request', model: 'kimi-test', time: now - 7_200_000 },
    { type: 'context.append_message', time: now - 7_100_000, message: { role: 'user', origin: { kind: 'user' }, content: [{ type: 'text', text: 'Past Kimi prompt' }] } },
    { type: 'context.append_loop_event', time: now - 7_000_000, event: { type: 'step.begin' } },
    { type: 'context.append_loop_event', time: now - 6_900_000, event: { type: 'content.part', part: { type: 'text', text: 'Kimi response' } } },
    { type: 'context.append_loop_event', time: now - 6_800_000, event: { type: 'step.end' } }
  ]);
  const old = new Date(now - 7_200_000);
  utimesSync(codexFile, old, old);
  utimesSync(kimiFile, old, old);
  const baseUrl = await startServer();
  const response = await fetch(`${baseUrl}/api/sessions`);
  assert.equal(response.status, 200);
  assert.match(response.headers.get('cache-control'), /no-store/);
  const data = await response.json();
  assert.equal(data.activeMinutes, 15);
  assert.equal(data.sessions.length, 3);
  assert.equal(data.sessions.filter(session => session.active).length, 1);
  assert.equal(data.sessions.filter(session => !session.active).length, 2);
  assert.equal('insights' in data, false);
  console.log('  ✓ --serve returns active and past sessions');

  const claude = data.sessions.find(session => session.source === 'claude');
  const codex = data.sessions.find(session => session.source === 'codex');
  const kimi = data.sessions.find(session => session.source === 'kimi');
  assert.equal(claude.active, true);
  assert.equal(claude.project, '/workspace/claude');
  assert.equal(claude.messageCount, 3);
  assert.equal(claude.firstPrompt, 'Active Claude prompt');
  assert.equal(claude.title, 'Active Claude prompt');
  assert.equal(claude.resumeCommand, `cd '/workspace/claude' && claude --resume '${CLAUDE_ID}'`);
  assert.equal(codex.active, false);
  assert.equal(codex.resumeCommand, `cd '/workspace/codex' && codex resume '${CODEX_ID}'`);
  assert.equal(kimi.active, false);
  assert.equal(kimi.project, '/workspace/kimi');
  assert.equal(kimi.title, 'Kimi dashboard fixture');
  assert.equal(kimi.messageCount, 2);
  assert.equal(kimi.model, 'kimi-test');
  assert.equal(kimi.resumeCommand, `cd '/workspace/kimi' && kimi --session 'session_${KIMI_ID}'`);
  assert.equal(kimi.viewCommand, `sessions show 'kimi:${KIMI_ID}'`);
  assert.equal('filePath' in kimi, false);
  for (const session of data.sessions) {
    assert.equal(session.activity.length, 7);
    assert.equal(session.activity.reduce((sum, day) => sum + day.count, 0), session.source === 'claude' ? 3 : 2);
  }
  console.log('  ✓ session metadata, seven-day activity, and resume commands are correct');

  appendFileSync(claudeFile, JSON.stringify(message('user', 'New live prompt')) + '\n');
  const refreshed = await (await fetch(`${baseUrl}/api/sessions`)).json();
  const refreshedClaude = refreshed.sessions.find(session => session.source === 'claude');
  assert.equal(refreshedClaude.messageCount, 4);
  assert.equal(refreshedClaude.userCount, 3);
  assert.equal(refreshedClaude.activity.reduce((sum, day) => sum + day.count, 0), 4);
  console.log('  ✓ new transcript activity appears on the next refresh');

  const recentResponse = await fetch(`${baseUrl}/api/sessions/claude/${CLAUDE_ID}/messages?limit=2`);
  assert.equal(recentResponse.status, 200);
  const recent = await recentResponse.json();
  assert.equal(recent.total, 4);
  assert.equal(recent.hasMore, true);
  assert.equal(recent.nextBefore, 2);
  assert.deepEqual(recent.messages.map(message => message.text), ['Claude response', 'New live prompt']);
  const earlier = await (await fetch(`${baseUrl}/api/sessions/claude/${CLAUDE_ID}/messages?limit=2&before=${recent.nextBefore}`)).json();
  assert.equal(earlier.hasMore, false);
  assert.equal(earlier.nextBefore, 0);
  assert(earlier.messages[0].text.includes('local-command-caveat'));
  assert.equal(earlier.messages[1].text, 'Active Claude prompt');
  assert.equal((await fetch(`${baseUrl}/api/sessions/claude/missing/messages`)).status, 404);
  console.log('  ✓ transcript previews page backward without hiding original messages');

  const htmlResponse = await fetch(`${baseUrl}/`);
  const html = await htmlResponse.text();
  assert.equal(htmlResponse.status, 200);
  assert.match(htmlResponse.headers.get('content-security-policy'), /default-src 'self'/);
  assert(html.includes('id="session-list"'));
  assert(!html.includes('id="analyze-button"'));
  assert(!html.includes('id="category-filter"'));
  assert(html.includes('Refreshes automatically every 60 seconds.'));
  assert(html.includes('/markdown.js'));
  assert.equal((await fetch(`${baseUrl}/markdown.js`)).status, 200);
  for (const face of ['ibm-plex-sans-400', 'ibm-plex-sans-500', 'ibm-plex-mono-400', 'ibm-plex-mono-500']) {
    const font = await fetch(`${baseUrl}/fonts/${face}.woff2`);
    assert.equal(font.status, 200);
    assert.equal(font.headers.get('content-type'), 'font/woff2');
    assert((await font.arrayBuffer()).byteLength > 10_000);
  }
  assert.equal((await fetch(`${baseUrl}/fonts/missing.woff2`)).status, 404);
  const styles = await (await fetch(`${baseUrl}/dashboard.css`)).text();
  assert(!/https?:\/\//.test(styles), 'the stylesheet loads nothing from outside this machine');
  const script = await (await fetch(`${baseUrl}/dashboard.js`)).text();
  assert(script.includes('Copy command'));
  assert(script.includes('createActivityChart'));
  assert(script.includes('Recent conversation'));
  assert(!script.includes('/api/insights'));
  assert(script.includes('60_000'));
  assert.equal((await fetch(`${baseUrl}/missing`)).status, 404);
  console.log('  ✓ dashboard assets and refresh behavior are served');

  assert.equal((await fetch(`${baseUrl}/api/insights`)).status, 404);
  const packedFiles = ['dashboard/dashboard.html', 'dashboard/dashboard.css', 'dashboard/dashboard.js', 'dashboard/markdown.js', 'lib/server.js'];
  for (const file of packedFiles) {
    assert(readFileSync(path.join(__dirname, '..', file), 'utf8').length > 0);
  }
  console.log('  ✓ local-only server exposes only the packaged dashboard assets');

  console.log('\n6 passed, 0 failed\n');
} finally {
  if (serverProcess && serverProcess.exitCode === null && serverProcess.signalCode === null) {
    const exited = once(serverProcess, 'exit');
    serverProcess.kill('SIGTERM');
    await exited;
  }
  rmSync(root, { recursive: true, force: true });
}
