// Query language and text helpers shared by both search backends: the
// Elasticsearch index (elastic.js) and the file scan (local-search.js).
// Keeping them here is what makes one query mean the same thing either way.

export const HIGHLIGHT_OPEN = '\u0001';
export const HIGHLIGHT_CLOSE = '\u0002';

// Besides whitespace, text is split into tokens on these characters. The ones
// left out (. - _ / : @ # + ~) stay inside a token, so paths, flags, and
// dotted or hyphenated names survive as one unit.
export const TOKEN_SPLIT_CHARS = ['(', ')', '[', ']', '{', '}', '<', '>', ',', ';', '"', '`', '=', '|', '!', '?', '*', '&', '^', '%', '$'];

export const MAX_TOOL_CALL_CHARS = 2_000;

// Tool inputs are flattened to their values, one per line. Serialized JSON
// would glue escape sequences onto neighboring words ("\nfoo" becomes "nfoo")
// and make every key name ("command", "file_path") match every call.
export function toolInputText(input) {
  if (input === null || input === undefined) return '';
  if (typeof input === 'string') return input.slice(0, MAX_TOOL_CALL_CHARS);
  const values = [];
  let length = 0;
  const walk = (value, depth) => {
    if (value === null || value === undefined || depth > 5 || length >= MAX_TOOL_CALL_CHARS) return;
    if (Array.isArray(value)) {
      for (const item of value) walk(item, depth + 1);
    } else if (typeof value === 'object') {
      for (const item of Object.values(value)) walk(item, depth + 1);
    } else if (typeof value === 'string' || typeof value === 'number') {
      const text = String(value);
      if (!text.trim()) return;
      values.push(text);
      length += text.length + 1;
    }
  };
  walk(input, 0);
  return values.join('\n').slice(0, MAX_TOOL_CALL_CHARS);
}

// Transcripts record plenty under the user role that the user never typed:
// task notifications, command output, reminders, and the summary a session
// resumes from. They stay searchable but do not rank as something asked.
export function isInjectedUserText(text) {
  const start = String(text).trimStart().slice(0, 200);
  return /^<[a-z][a-z0-9_-]*[\s>]/.test(start) ||
    start.startsWith('Caveat: The messages below were generated by the user') ||
    start.startsWith('This session is being continued from a previous conversation') ||
    start.startsWith('[Request interrupted by user');
}

// --- query language ---

// A term made only of characters the tokenizer splits on ("|", "&&", "=")
// produces no tokens and so can never match as a word.
export function hasTokens(text) {
  for (const char of text) {
    if (!/\s/.test(char) && !TOKEN_SPLIT_CHARS.includes(char)) return true;
  }
  return false;
}

// Turns one bare word into query items. People who search transcripts often
// write grep patterns, so two of those are understood here:
//   a\|b or a|b   either side
//   a.*b          both, a before b, in the same stretch of text
function wordItems(word) {
  const alternatives = word.includes('\\|') ? word.split('\\|') : word.split('|');
  const usable = alternatives.every(part => hasTokens(part));
  const parts = usable ? alternatives : [word];
  const items = [];
  parts.forEach((part, position) => {
    if (position > 0) items.push({ type: 'operator', text: 'OR' });
    const pieces = part.replace(/\\(?=[^\w\s])/g, '').split('.*').filter(hasTokens);
    if (pieces.length > 1) items.push({ type: 'near', text: pieces.join(' ') });
    else if (pieces.length === 1) items.push({ type: 'term', text: pieces[0] });
  });
  return items;
}

// Parses a search string into AND-ed groups of OR-ed alternatives.
//   words          every word must appear (inflections count)
//   "exact words"  the words in that order, no inflections
//   a OR b         either side
//   NOT word       excludes messages containing it
// The operators are uppercase words on purpose: "-" is far too common in the
// flags and names people search for to mean "exclude".
export function parseQuery(input) {
  const items = [];
  const text = String(input || '');
  let i = 0;
  while (i < text.length) {
    if (/\s/.test(text[i])) { i++; continue; }
    if (text[i] === '"') {
      const end = text.indexOf('"', i + 1);
      const phrase = (end === -1 ? text.slice(i + 1) : text.slice(i + 1, end)).trim();
      i = end === -1 ? text.length : end + 1;
      if (hasTokens(phrase)) items.push({ type: 'phrase', text: phrase });
      continue;
    }
    let end = i;
    while (end < text.length && !/\s/.test(text[end]) && text[end] !== '"') end++;
    const word = text.slice(i, end);
    i = end;
    if (word === 'OR' || word === 'NOT' || word === 'AND') items.push({ type: 'operator', text: word });
    else items.push(...wordItems(word));
  }

  const groups = [];
  const excluded = [];
  let negate = false;
  let joinWithPrevious = false;
  for (let index = 0; index < items.length; index++) {
    const item = items[index];
    if (item.type === 'operator') {
      const hasOperand = items.slice(index + 1).some(next => next.type !== 'operator');
      if (!hasOperand) {
        // A trailing operator has nothing to act on, so it is a plain word.
        groups.push([{ type: 'term', text: item.text }]);
        continue;
      }
      if (item.text === 'NOT') negate = true;
      else if (item.text === 'OR') joinWithPrevious = groups.length > 0;
      continue;
    }
    if (negate) {
      excluded.push(item);
      negate = false;
      joinWithPrevious = false;
      continue;
    }
    if (joinWithPrevious) groups[groups.length - 1].push(item);
    else groups.push([item]);
    joinWithPrevious = false;
  }

  return { groups, excluded };
}
